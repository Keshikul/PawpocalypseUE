"""Writes Content/Pawpocalypse/Localization/Strings/ST_Data.csv, the string table of data-driven names (docs/08 §4).

Data rows carry no label columns at runtime: the player-facing name of an upgrade, a biome or a boss is a string-table row
keyed by convention from its id (`UPG_<id>_name`, `TIER_<id>_name`, `BOSS_<id>_name`, `CARD_<id>_name` / `_desc`,
`ACH_<id>_name` / `_desc`, `JOB_<id>_name` / `_desc`, `SKILL_<id>_name`), its English source the column exported from Godot
into Data/*.csv. A card's description keeps Godot's `{v}` / `{c}` (value and cost), which FText::Format fills by name.
SKILL names are the branches' `display_name`; the skill tree screen draws `BRANCH_LABELS` instead (ST_Tree, generated by
tools/gen_tree_tables.py), which differ for one node (`overkill`: "Splash").

    py tools/gen_data_strings.py [--check]
"""
import argparse
import csv
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "Data"
OUT = ROOT / "Content" / "Pawpocalypse" / "Localization" / "Strings" / "ST_Data.csv"

# (prefix, csv, [(key suffix, the column holding the English)])
AREAS = [
    ("UPG", "UpgradeData.csv", [("name", "display_name")]),
    ("TIER", "TierData.csv", [("name", "display_name")]),
    ("BOSS", "BossData.csv", [("name", "display_name")]),
    ("CARD", "CardData.csv", [("name", "display_name"), ("desc", "description")]),
    ("ACH", "AchievementData.csv", [("name", "display_name"), ("desc", "description")]),
    ("JOB", "JobData.csv", [("name", "display_name"), ("desc", "description")]),
    ("SKILL", "SkillBranchData.csv", [("name", "display_name")]),
]


def render():
    out = io.StringIO()
    w = csv.writer(out, lineterminator="\n", quoting=csv.QUOTE_ALL)
    w.writerow(["Key", "SourceString", "Comment"])
    for prefix, name, fields in AREAS:
        with open(DATA / name, encoding="utf-8", newline="") as f:
            for row in csv.DictReader(f):
                for suffix, column in fields:
                    w.writerow(["%s_%s_%s" % (prefix, row["id"], suffix), row[column],
                                "Data/%s %s %s" % (name, row["id"], column)])
    return out.getvalue()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = OUT.read_bytes().decode("utf-8") if OUT.exists() else ""
        if current != text:
            print("ST_Data.csv is not what tools/gen_data_strings.py writes: re-run it")
            return 1
        print("ST_Data.csv current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(text.encode("utf-8"))
    print("wrote %s (%d rows)" % (OUT.relative_to(ROOT), text.count("\n") - 1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
