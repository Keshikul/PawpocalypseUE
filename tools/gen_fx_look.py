"""Writes Source/Pawpocalypse/Realm/PawFxLook.h: the field effects' look from tools/art (restyle D3, tools/art/fx_look.py).

  - the aura's lift and ring, the crit colour: sRGB floats (FPawFxCanvas takes Godot Colors), from tools/art/palette.py;
  - the strike paw: ui_cursor_paw_closed's drawing (tools/art/make_sweet_art.py _cursor_paw), shape by shape in its draw
    order, ellipses tessellated, in the drawing's 128-unit box; a stroked shape is its fill then an ink outline
    (sweet_shapes.to_svg draws stroke INK at STROKE). FPawFxCanvas draws convex polygons, and every shape here is one.

When the cursor is redrawn (R6), re-run this and the strike paw follows.

    py tools/gen_fx_look.py [--check]
"""
import argparse
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "art"))
import fx_look as FX  # noqa: E402
import make_sweet_art as ART  # noqa: E402
import palette as PAL  # noqa: E402
import sweet_shapes as S  # noqa: E402

OUT = ROOT / "Source" / "Pawpocalypse" / "Realm" / "PawFxLook.h"
ELLIPSE_POINTS = 24


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def godot(h, a=1.0):
    r, g, b = rgb(h)
    return "FLinearColor(%.6ff, %.6ff, %.6ff, %.6ff)" % (r / 255.0, g / 255.0, b / 255.0, a)


def outline(p):
    if p["k"] == "ell":
        return [(p["cx"] + p["rx"] * math.cos(2 * math.pi * i / ELLIPSE_POINTS),
                 p["cy"] + p["ry"] * math.sin(2 * math.pi * i / ELLIPSE_POINTS)) for i in range(ELLIPSE_POINTS)]
    if p["k"] == "tri":
        return list(p["pts"])
    raise SystemExit("the strike paw holds a %r shape; PawFxLook draws ellipses and triangles only" % p["k"])


def render():
    parts = ART._cursor_paw(True)
    points, rows = [], []
    for p in parts:
        pts = outline(p)
        first = len(points)
        points += pts
        rows.append((first, len(pts), p["fill"], False))
        if p.get("s", True):
            rows.append((first, len(pts), S.INK, True))
    L = []
    L.append("#pragma once")
    L.append("")
    L.append("// GENERATED by tools/gen_fx_look.py from tools/art (fx_look.py, palette.py, make_sweet_art.py). Do not edit: change")
    L.append("// the look there, then re-run the generator. The field effects' look, restyle D3 (designer, 2026-11-09): the aura")
    L.append("// lifted with a Bone ring, the clutching paw riding the strike, crits in Butter. Colours are Godot Colors (sRGB")
    L.append("// floats, straight alpha), as FPawFxCanvas takes them.")
    L.append("")
    L.append('#include "CoreMinimal.h"')
    L.append("")
    L.append("namespace PawFxLook")
    L.append("{")
    L.append("\t// The aura (D): a white lift inside, a Bone ring with a Plum ink edge.")
    L.append("\tinline const FLinearColor AuraLift = %s;" % godot(FX.AURA_LIFT, FX.AURA_LIFT_ALPHA))
    L.append("\tinline const FLinearColor AuraRing = %s;" % godot(FX.AURA_RING))
    L.append("\tinline constexpr double AuraRingWidth = %.3f;" % FX.AURA_RING_WIDTH)
    L.append("\tinline constexpr double AuraInkEdge = %.3f;" % FX.AURA_INK_EDGE)
    L.append("\tinline constexpr double AuraInkAlpha = %.3f;" % FX.AURA_INK_ALPHA)
    L.append("")
    L.append("\t// Crits and earned crits (Godot's pink is the reward colour).")
    L.append("\tinline const FLinearColor Crit = %s;" % godot(FX.CRIT))
    L.append("")
    L.append("\t// The strike paw (S3): ui_cursor_paw_closed's drawing at the arc's tip, toes along the motion.")
    L.append("\tinline constexpr double StrikePawPx = %.3f;       // the drawing's box in field px" % FX.STRIKE_PAW_PX)
    L.append("\tinline constexpr double StrikePawBox = %.3f;      // the drawing's units" % S.SIZE)
    L.append("\tinline constexpr double StrikePawStroke = %.3f;    // its ink outline, in drawing units" % S.STROKE)
    L.append("\tinline constexpr double StrikeArcTrail = %.3f;     // the arc behind the paw, a share of Godot's" % FX.STRIKE_ARC_TRAIL)
    L.append("\tinline constexpr double StrikePawFadeGain = %.3f;  // the paw's opacity: min(1, the swipe's x this)" % FX.STRIKE_PAW_FADE_GAIN)
    L.append("")
    L.append("\tstruct FStrikePawPart")
    L.append("\t{")
    L.append("\t\tint32 First;  // into StrikePawPoints")
    L.append("\t\tint32 Count;")
    L.append("\t\tuint8 R, G, B; // sRGB")
    L.append("\t\tbool bOutline; // false: a filled convex polygon; true: its closed ink outline, StrikePawStroke wide")
    L.append("\t};")
    L.append("\tinline constexpr double StrikePawPoints[][2] = {")
    for i in range(0, len(points), 4):
        L.append("\t\t" + " ".join("{ %.4f, %.4f }," % xy for xy in points[i:i + 4]))
    L.append("\t};")
    L.append("\tinline constexpr FStrikePawPart StrikePawParts[] = {")
    for first, count, col, ol in rows:
        r, g, b = rgb(col)
        L.append("\t\t{ %d, %d, %d, %d, %d, %s }," % (first, count, r, g, b, "true" if ol else "false"))
    L.append("\t};")
    L.append("}")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != text:
            print("%s is not what tools/gen_fx_look.py writes: re-run it" % OUT.relative_to(ROOT))
            return 1
        print("PawFxLook.h current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s" % OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
