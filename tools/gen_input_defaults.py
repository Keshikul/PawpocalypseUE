"""Writes Source/Pawpocalypse/Input/PawInputDefaults.h: Godot's input map as the game needs it at run time (docs/05 §3).

Remapping (PawCore PcBindings) works on Godot's events: the defaults a rebind starts from, compares with (the saved diff) and
resets to are Godot's own, keypad Enter included (Unreal merges it into Enter, so IMC_Pawpocalypse cannot hold it). Data/
InputMap.csv is not cooked; this header is its Godot side, one row per event, in the CSV's (project.godot's) order, with the
action's dead zone. PawInput::DefaultState() puts them in Godot's InputMap order (Pc::BindingGodotOrder).

    py tools/gen_input_defaults.py [--check]
"""
import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "Data" / "InputMap.csv"
OUT = ROOT / "Source" / "Pawpocalypse" / "Input" / "PawInputDefaults.h"


def render():
    with open(CSV, encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    lines = [
        "#pragma once",
        "",
        "// GENERATED by tools/gen_input_defaults.py from Data/InputMap.csv: do not edit (re-run the script; the L0 gate checks it).",
        "// Godot's input map, one row per event in project.godot's order: the defaults remapping starts from (PawInput::DefaultState).",
        "",
        "#include \"CoreMinimal.h\"",
        "",
        "struct FPawInputDefault",
        "{",
        "\tconst char* Action;",
        "\tconst char* GodotEvent; // key | mouse_button | pad_button | pad_axis",
        "\tint64 GodotCode;",
        "\tint32 GodotAxisSign;     // a pad axis: -1 or 1 (Godot's axes: +Y is DOWN), else 0",
        "\tfloat DeadZone;          // the action's",
        "};",
        "",
        "inline constexpr FPawInputDefault PawInputDefaults[] = {",
    ]
    for r in rows:
        sign = r["godot_axis_sign"] or "0"
        lines.append('\t{ "%s", "%s", %s, %s, %sf },' % (r["action"], r["godot_event"], r["godot_code"], sign, r["deadzone"]))
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the header is not what the CSV gives")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("STALE: %s (run py tools/gen_input_defaults.py)" % OUT.relative_to(ROOT))
            return 1
        print("OK    %s" % OUT.relative_to(ROOT))
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s (%d events)" % (OUT.relative_to(ROOT), text.count("\t{ ")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
