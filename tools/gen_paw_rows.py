"""Writes Source/Pawpocalypse/Data/PawDataRows.h: one DataTable row struct per Data/*.csv (docs/06 §4), plus the table list.

Every column is an FString holding the CSV cell's TEXT, exactly as written. The DataTable importer stores an FString cell
verbatim (FStrProperty::ImportText without PPF_Delimited, UE 5.8.3), so a table holds the same text as its CSV, and the
game turns it into numbers with the SAME parser the tests, pawsim's mirror and pawcore_sim use (FPawDataAdapter rebuilds
PawCore CsvTables from the rows and calls Pc::BuildGameData). One parser means the DataTable route cannot read a number
differently from the CSV route; the typed view of the data is PawCore's PcGameData, not the table.

Columns are the CSV header (after the row-name column `id`), property names are the column names (snake_case on purpose:
the importer matches header to property). `_godot_file` is imported as `godot_file` (tools/import_data.py renames the
header; a C++ identifier should not start with an underscore), and the adapter maps it back.

    py tools/gen_paw_rows.py [--check]
"""
import argparse
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "Data")
OUT = os.path.join(ROOT, "Source", "Pawpocalypse", "Data", "PawDataRows.h")
ASSET_DIR = "/Game/Pawpocalypse/Data"
# Source, not data: the reviewed list tools/export_code_constants.py reads.
NOT_TABLES = {"CodeConstantsMap.csv"}


def struct_name(csv_name: str) -> str:
    base = csv_name[:-4] if csv_name.endswith("Data") else csv_name
    return "FPaw%sRow" % base


def property_name(column: str) -> str:
    return "godot_file" if column == "_godot_file" else column


def tables():
    out = []
    for fn in sorted(os.listdir(DATA)):
        if not fn.endswith(".csv") or fn in NOT_TABLES:
            continue
        with open(os.path.join(DATA, fn), newline="", encoding="utf-8") as f:
            header = next(csv.reader(f))
        if header[0] != "id":
            raise SystemExit("%s: the first column must be id (it becomes the row name)" % fn)
        out.append((fn[:-4], header[1:]))
    return out


def generate() -> str:
    lines = [
        "#pragma once",
        "",
        "// GENERATED by tools/gen_paw_rows.py from the Data/*.csv headers. Do not edit; regenerate.",
        "// One DataTable row struct per CSV; every column is the cell's TEXT, parsed by PawCore (Data/PawDataAdapter.h).",
        "// Property names are the CSV column names on purpose: the DataTable importer matches the header to them.",
        "",
        '#include "CoreMinimal.h"',
        '#include "Engine/DataTable.h"',
        "",
        '#include "PawDataRows.generated.h"',
        "",
    ]
    listed = []
    for name, columns in tables():
        s = struct_name(name)
        lines += [
            "// Data/%s.csv -> %s/DT_%s" % (name, ASSET_DIR, name),
            "USTRUCT()",
            "struct %s : public FTableRowBase" % s,
            "{",
            "\tGENERATED_BODY()",
            "",
        ]
        for c in columns:
            lines.append('\tUPROPERTY(VisibleAnywhere, Category = "Data")')
            lines.append("\tFString %s;" % property_name(c))
        lines += ["};", ""]
        listed.append((name, s))
    lines += [
        "// Every table: the CSV it is imported from (Data/<CsvName>.csv), its asset, its row struct.",
        "struct FPawDataTableInfo",
        "{",
        "\tconst TCHAR* CsvName;",
        "\tconst TCHAR* AssetPath;",
        "\tUScriptStruct* (*RowStruct)();",
        "};",
        "",
        "inline TConstArrayView<FPawDataTableInfo> PawDataTables()",
        "{",
        "\tstatic const FPawDataTableInfo Tables[] = {",
    ]
    for name, s in listed:
        lines.append('\t\t{ TEXT("%s"), TEXT("%s/DT_%s.DT_%s"), &%s::StaticStruct },' % (name, ASSET_DIR, name, name, s))
    lines += ["\t};", "\treturn Tables;", "}", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the header is not what this script would write")
    a = ap.parse_args()
    text = generate()
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if a.check:
        if old != text:
            print("%s is stale: run py tools/gen_paw_rows.py" % OUT)
            return 1
        print("PawDataRows.h is current")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d tables)" % (OUT, len(tables())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
