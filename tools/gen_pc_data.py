"""Writes Source/PawCore/Public/PcDataRows.h: one plain struct per data class + its CSV row reader.

Fields, types and DEFAULTS come from the Godot data scripts (read-only), because an empty CSV cell means "the .tres did not
set it" = the script's default; typing ~150 defaults by hand is the drift docs/06 warns about. Checks while generating:
every CSV column (except the exporter's `_godot_file`) is a script field and every field is a column, or it refuses.

Types: float -> double (never float, hard rule), int -> int64_t, bool, String -> std::string, Color -> std::array<double, 4>,
Array[float] -> std::vector<double>, Array[String] / Array[<Resource>] -> std::vector<std::string> (ids), <Resource> -> id
string, Dictionary (only SkillBranchData.extra_effects: name -> float ladder) -> std::map<std::string, std::vector<double>>,
enums -> the PcEnums.h types.

    py tools/gen_pc_data.py [--godot C:/Games/pawpocalypse] [--check]
"""
import argparse
import csv
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from godot_fixes import fixed_read  # noqa: E402  (D16/D17: the port's fixes to Godot's scripts, e.g. E3's new field)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Source", "PawCore", "Public", "PcDataRows.h")

# CSV class -> (Godot script, C++ struct, enum prefix used by gen_pc_enums.py)
CLASSES = [
    ("TierData", "tier_data.gd", "PcTier", ""),
    ("EnemyData", "enemy_data.gd", "PcEnemy", "Enemy"),
    ("BossData", "boss_data.gd", "PcBoss", ""),
    ("UpgradeData", "upgrade_data.gd", "PcUpgrade", "Upgrade"),
    ("SkillBranchData", "skill_branch_data.gd", "PcSkillBranch", "Branch"),
    ("EvolutionData", "evolution_data.gd", "PcEvolution", "Evolution"),
    ("CardData", "card_data.gd", "PcCard", "Card"),
    ("JobData", "job_data.gd", "PcJob", ""),
    ("AchievementData", "achievement_data.gd", "PcAchievement", "Achievement"),
    ("CombatConstantsData", "combat_constants_data.gd", "PcCombatConstants", ""),
    ("ReawakenConstantsData", "reawaken_constants_data.gd", "PcReawakenConstants", ""),
]
RE_FIELD = re.compile(r"^@export(?:_\w+(?:\([^)]*\))?)?\s+var\s+(\w+)\s*:\s*([\w\[\]]+)\s*(?:=\s*(.*?))?\s*(?:##.*)?$")
RE_ENUM = re.compile(r"^enum\s+(\w+)")
RESOURCES = {"EnemyData", "BossData"}


def pascal(name: str, cpp_type: str) -> str:
    p = "".join(w[:1].upper() + w[1:] for w in name.split("_"))
    return ("b" + p) if cpp_type == "bool" else p


def num(text: str, is_int: bool) -> str:
    text = text.strip()
    if is_int:
        return str(int(float(text)))
    return text if re.search(r"[.eE]", text) else text + ".0"


def color(text: str) -> str:
    text = text.strip()
    if text in ("Color.WHITE", ""):
        return "{ 1.0, 1.0, 1.0, 1.0 }"
    m = re.match(r"Color\(([^)]*)\)", text)
    parts = [num(x, False) for x in m.group(1).split(",")]
    while len(parts) < 4:
        parts.append("1.0")
    return "{ " + ", ".join(parts) + " }"


def field_cpp(gd_type: str, default, enums: set, prefix: str):
    """-> (cpp type, default initialiser, reader helper)"""
    d = (default or "").strip()
    if gd_type == "float":
        return "double", num(d or "0.0", False), "ReadDouble"
    if gd_type == "int":
        return "int64_t", num(d or "0", True), "ReadInt"
    if gd_type == "bool":
        return "bool", d or "false", "ReadBool"
    if gd_type in ("String", "StringName"):
        return "std::string", d or '""', "ReadString"
    if gd_type == "Color":
        return "std::array<double, 4>", color(d), "ReadColor"
    if gd_type == "Array[float]":
        items = [num(x, False) for x in d.strip("[]").split(",") if x.strip()] if d else []
        return "std::vector<double>", "{ " + ", ".join(items) + " }" if items else "{}", "ReadDoubleList"
    if gd_type == "Array[String]" or (gd_type.startswith("Array[") and gd_type[6:-1] in RESOURCES):
        return "std::vector<std::string>", "{}", "ReadStringList"
    if gd_type in RESOURCES:
        return "std::string", '""', "ReadString"
    if gd_type == "Dictionary":
        return "std::map<std::string, std::vector<double>>", "{}", "ReadLadderMap"
    if gd_type in enums:
        cpp = prefix + gd_type
        value = d.split(".")[-1]
        return cpp, f"{cpp}::{value}", "ReadEnum"
    raise SystemExit(f"unsupported Godot type {gd_type}")


def generate(godot: str) -> str:
    out = [
        "#pragma once",
        "",
        "// GENERATED by tools/gen_pc_data.py from the Godot data scripts (fields, types, defaults) and checked against",
        "// Data/*.csv headers. Do not edit; regenerate. One struct per data class + its row reader (PcData.cpp calls them).",
        "",
        "#include \"PcCore.h\"",
        "#include \"PcEnums.h\"",
        "#include \"PcCsv.h\"",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <map>",
        "#include <string>",
        "#include <vector>",
        "",
        "namespace Pc",
        "{",
    ]
    for cls, script, struct, prefix in CLASSES:
        gd = fixed_read(godot, os.path.join(godot, "scripts", "data", script)).replace("\r\n", "\n")
        enums = {m.group(1) for m in map(RE_ENUM.match, (l.strip() for l in gd.splitlines())) if m}
        fields = []
        for line in gd.splitlines():
            m = RE_FIELD.match(line.strip())
            if m:
                name, gd_type, default = m.groups()
                cpp_type, init, reader = field_cpp(gd_type, default, enums, prefix)
                fields.append((name, pascal(name, cpp_type), cpp_type, init, reader))
        # The exporter names singleton rows (combat/reawaken constants have no `id` in Godot): every row has an id.
        if "id" not in [f[0] for f in fields]:
            fields.insert(0, ("id", "Id", "std::string", '""', "ReadString"))
        header = next(csv.reader(open(os.path.join(ROOT, "Data", cls + ".csv"), encoding="utf-8", newline="")))
        cols = [c for c in header if c != "_godot_file"]
        names = [f[0] for f in fields]
        missing, extra = sorted(set(names) - set(cols)), sorted(set(cols) - set(names))
        if extra:
            raise SystemExit(f"{cls}: CSV columns without a script field {extra}")
        out.append(f"\t// {cls} ({script})")
        if missing:
            # The exporter writes a column only if some .tres sets the field; a field at its default everywhere has none.
            out.append(f"\t// No CSV column (the default everywhere): {', '.join(missing)}")
        out.append(f"\tstruct {struct}")
        out.append("\t{")
        for _, member, cpp_type, init, _ in fields:
            out.append(f"\t\t{cpp_type} {member} = {init};")
        out.append("\t};")
        out.append("")
        out.append(f"\t// Reads one row; an empty cell keeps the Godot default. Problems are appended to Errors, never thrown.")
        out.append(f"\tinline void ReadRow(const CsvTable& T, size_t Row, {struct}& Out, std::vector<std::string>& Errors)")
        out.append("\t{")
        out.append(f"\t\tconst CsvRowReader R(T, Row, \"{cls}\", Errors);")
        for name, member, _, _, reader in fields:
            out.append(f"\t\tR.{reader}(\"{name}\", Out.{member});")
        out.append("\t}")
        out.append("")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--godot", default="C:/Games/pawpocalypse")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = generate(a.godot)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if a.check:
        print("PcDataRows.h up to date" if old == text else "PcDataRows.h is stale: run py tools/gen_pc_data.py")
        return 0 if old == text else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
