"""Writes Source/PawCore/Public/PcEnums.h from the Godot data scripts' enums (read-only).

Data stores enums by NAME (docs/06 §3); C++ needs real enums. This generates one `enum class` per Godot enum with the Godot
numeric values (gaps kept, so a value never shifts) and a name table, plus FromName/ToName helpers. Regenerate when a Godot
enum gains a value (append-only: renaming or reordering a value is a save/data break and the generator refuses it).

    py tools/gen_pc_enums.py [--godot C:/Games/pawpocalypse] [--check]
--check: exit 1 if the header on disk differs from what would be generated (a gate in tools/check_all.ps1).
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from export_godot_data import parse_enums  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Source", "PawCore", "Public", "PcEnums.h")

# Godot script -> C++ name prefix. Two scripts both define EffectType: the prefix keeps them apart.
SOURCES = [
    ("upgrade_data.gd", "Upgrade"),
    ("enemy_data.gd", "Enemy"),
    ("evolution_data.gd", "Evolution"),
    ("skill_branch_data.gd", "Branch"),
    ("card_data.gd", "Card"),
    ("achievement_data.gd", "Achievement"),
]


def generate(godot: str) -> str:
    lines = [
        "#pragma once",
        "",
        "// GENERATED by tools/gen_pc_enums.py from the Godot data scripts. Do not edit; regenerate.",
        "// Values are the Godot enum values (gaps kept). Data and saves store the NAME (docs/06 §3): never rename a value.",
        "",
        "#include \"PcCore.h\"",
        "",
        "#include <cstdint>",
        "#include <string>",
        "",
        "namespace Pc",
        "{",
    ]
    for script, prefix in SOURCES:
        enums = parse_enums(open(os.path.join(godot, "scripts", "data", script), encoding="utf-8").read())
        for name, values in enums.items():
            cpp = prefix + name
            lines.append(f"\t// {script}: {name}")
            lines.append(f"\tenum class {cpp} : int32_t")
            lines.append("\t{")
            for i, v in enumerate(values):
                if v:
                    lines.append(f"\t\t{v} = {i},")
            lines.append("\t};")
            lines.append("")
            lines.append(f"\tinline const char* ToName({cpp} V)")
            lines.append("\t{")
            lines.append("\t\tswitch (V)")
            lines.append("\t\t{")
            for v in values:
                if v:
                    lines.append(f"\t\tcase {cpp}::{v}: return \"{v}\";")
            lines.append("\t\t}")
            lines.append("\t\treturn \"\";")
            lines.append("\t}")
            lines.append("")
            lines.append(f"\t// False (and Out untouched) for an unknown name: the loader reports it, never guesses.")
            lines.append(f"\tinline bool FromName(const std::string& Name, {cpp}& Out)")
            lines.append("\t{")
            for i, v in enumerate(values):
                if v:
                    lines.append(f"\t\tif (Name == \"{v}\") {{ Out = {cpp}::{v}; return true; }}")
            lines.append("\t\treturn false;")
            lines.append("\t}")
            lines.append("")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--godot", default="C:/Games/pawpocalypse")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = generate(a.godot)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if a.check:
        if old != text:
            print("PcEnums.h is stale: run py tools/gen_pc_enums.py")
            return 1
        print("PcEnums.h up to date")
        return 0
    # Append-only: every (enum, name) already in the header must keep its value.
    import re
    for enum, body in re.findall(r"enum class (\w+) : int32_t\s*\{(.*?)\};", old, re.S):
        for name, value in re.findall(r"(\w+) = (\d+),", body):
            if f"{name} = {value}," not in re.search(rf"enum class {enum} : int32_t\s*\{{(.*?)\}};", text, re.S).group(1):
                print(f"REFUSED: {enum}::{name} = {value} would change or disappear (enums are append-only)")
                return 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
