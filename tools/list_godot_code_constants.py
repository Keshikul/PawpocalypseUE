"""List every numeric/colour `const` in the Godot game's scripts: the tunables that live in CODE, not in /data.

The port must carry each one (into Data/CodeConstants.csv or a PawCore header with its reason). Without this list they are the
numbers most likely to be lost, because nothing else enumerates them.

    py tools/list_godot_code_constants.py --godot C:/Games/pawpocalypse --out docs/appendix-c-code-constants.md
"""
from __future__ import annotations

import argparse
import os
import re

RE_CONST = re.compile(r'^\s*const\s+([A-Z][A-Z0-9_]*)\s*(?::\s*[\w\[\]]+)?\s*:?=\s*(.+?)\s*(?:#\s*(.*))?$')
NUMERIC = re.compile(r'^[-+]?(\d+\.?\d*(e[-+]?\d+)?|\.\d+)(\s*[-+*/]\s*[-+]?\d+\.?\d*)*$', re.I)
COLOR = re.compile(r'^(Color\(|Palette\.)')
SKIP_DIRS = {"ci"}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--godot", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    rows = []
    scripts = os.path.join(a.godot, "scripts")
    for d, _, files in os.walk(scripts):
        for fn in sorted(files):
            if not fn.endswith(".gd"):
                continue
            path = os.path.join(d, fn)
            rel = os.path.relpath(path, a.godot).replace(os.sep, "/")
            with open(path, encoding="utf-8") as f:
                lines = f.read().splitlines()
            for i, line in enumerate(lines, 1):
                m = RE_CONST.match(line)
                if not m:
                    continue
                name, value, comment = m.group(1), m.group(2).strip(), (m.group(3) or "").strip()
                kind = "number" if NUMERIC.match(value) else "colour" if COLOR.match(value) else None
                if kind is None:
                    continue
                # nearest preceding ## doc comment, for the reason
                j, why = i - 2, []
                while j >= 0 and lines[j].strip().startswith("##"):
                    why.insert(0, lines[j].strip().lstrip("#").strip())
                    j -= 1
                reason = comment or " ".join(why)
                rows.append((rel, i, name, value, kind, reason))
    rows.sort(key=lambda r: (r[0], r[1]))
    out = [
        "# Appendix C - Gameplay constants that live in Godot CODE (generated)",
        "",
        "> Generated by `tools/list_godot_code_constants.py` from the Godot `scripts/` folder. These are tunables NOT in `/data`, so",
        "> `Data/*.csv` does not carry them. Each must be ported deliberately (doc 06 §5): gameplay numbers into `Data/CodeConstants.csv`,",
        "> presentation numbers (sizes, colours, timings of effects) into the C++ class that owns them, with the Godot reason as the",
        "> comment. `Palette.*` colours come from the generated token header instead.",
        "",
        f"{len(rows)} constants.",
        "",
        "| file:line | name | value | reason (Godot comment) |",
        "|---|---|---|---|",
    ]
    for rel, line, name, value, kind, reason in rows:
        reason = reason.replace("|", "\\|")
        if len(reason) > 160:
            reason = reason[:157] + "..."
        out.append(f"| `{rel}:{line}` | `{name}` | `{value}` | {reason} |")
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(rows)} constants -> {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
