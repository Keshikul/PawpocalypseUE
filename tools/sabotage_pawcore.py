def in_file_endings(text, s):
    # Targets are written with "\n"; a CRLF source (PcField.cpp, PcFormat.cpp, PcHud.cpp are) holds "\r\n". Counting on read_text (which
    # normalizes) while replacing in the raw bytes let every multi-line target pass the stale check and never land: 38
    # sabotages reported MISSED on unchanged code (nightly 2026-11-02). Count and replace in the same, raw text.
    return s.replace("\n", "\r\n") if "\r\n" in text else s


def build():
    r = subprocess.run(BUILD, capture_output=True, text=True)
    return r.returncode == 0, r.stdout + r.stderr


def run(test_filter, scale):
    env = dict(os.environ)
    env["PAWCORE_LONG_SCALE"] = scale
    env["PAWCORE_DATA_DIR"] = str(ROOT / "Data")
    r = subprocess.run([str(EXE), "--no-skip", "-tc=" + test_filter], capture_output=True, text=True, env=env)
    ran = "test cases:      0" not in r.stdout and "test cases: 0" not in r.stdout
    return r.returncode, ran, r.stdout


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", action="append")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()
    chosen = [s for s in SABOTAGES if not args.only or s[0] in args.only]
    unknown = set(args.only or []) - {s[0] for s in SABOTAGES}
    if unknown:
        print("unknown sabotage(s): %s" % ", ".join(sorted(unknown)))
        return 2
    # Every target must occur exactly once BEFORE anything is built: a stale target is a script bug, not a missed
    # sabotage, and a target that occurs twice would sabotage the wrong line (HANDOFF-LOG (13)).
    stale = []
    for name, file, old, *_ in SABOTAGES if args.list else chosen:
        raw = (PRIVATE / file).read_bytes().decode("utf-8")
        count = raw.count(in_file_endings(raw, old))
        if count != 1:
            stale.append("%-34s target occurs %d times in %s" % (name, count, file))
    # doctest splits -tc on commas: a filter with one matches no test, which reads as MISSED and a failing clean build.
    for name, _, _, _, test_filter, _ in SABOTAGES if args.list else chosen:
        if "," in test_filter:
            stale.append("%-34s test filter %r contains a comma (doctest splits -tc on commas)" % (name, test_filter))
    if args.list:
        for s in SABOTAGES:
            print("%-34s %-18s -> %s" % (s[0], s[1], s[4]))
    if stale:
        print("STALE: update these targets in tools/sabotage_pawcore.py (nothing was built or run):")
        for line in stale:
            print("  " + line)
        return 2
    if args.list:
        return 0

    missed = []
    for name, file, old, new, test_filter, scale in chosen:
        path = PRIVATE / file
        original = path.read_bytes()
        text = original.decode("utf-8")
        try:
            sabotaged = text.replace(in_file_endings(text, old), in_file_endings(text, new), 1)
            if sabotaged == text:
                # Confirm the sabotage LANDED (docs/09 §1): unchanged code is not a test of anything.
                print("NOLAND   %-26s the target was not replaced; nothing was built" % name, flush=True)
                missed.append(name)
                continue
            path.write_bytes(sabotaged.encode("utf-8"))
            ok, log = build()
            if not ok:
                print("NOBUILD  %-26s the sabotaged source does not compile:\n%s" % (name, log[-2000:]))
                missed.append(name)
                continue
            code, ran, out = run(test_filter, scale)
            caught = ran and code != 0
            print("%s %-26s %s" % ("CAUGHT  " if caught else "MISSED  ", name, test_filter), flush=True)
            if not caught:
                missed.append(name)
        finally:
            path.write_bytes(original)

    ok, log = build()
    clean_ok = ok
    if ok:
        for f in sorted({s[4] for s in chosen}):
            code, ran, out = run(f, "0.01")
            if code != 0 or not ran:
                clean_ok = False
                print("FAILS    clean build: %s" % f)
    print("%s  the clean sources" % ("PASS    " if clean_ok else "FAIL    "))
    if missed or not clean_ok:
        print("FAIL  %d sabotage(s) not caught: %s" % (len(missed), ", ".join(missed)))
        return 1
    print("PASS  all %d sabotages caught; the clean build passes" % len(chosen))
    return 0


if __name__ == "__main__":
    sys.exit(main())
