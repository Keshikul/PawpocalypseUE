def in_file_endings(text, s):
    # Targets are written with "\n"; count and replace in the file's own endings (the CRLF trap, sabotage_pawcore.py).
    return s.replace("\n", "\r\n") if "\r\n" in text else s


def build():
    r = subprocess.run(UBT, capture_output=True, text=True, encoding="utf-8", errors="replace")
    out = r.stdout + r.stderr
    return r.returncode == 0 and "Result: Succeeded" in out, out


def run(test):
    r = subprocess.run(AUTOMATION + [test], capture_output=True, text=True, encoding="utf-8", errors="replace")
    out = r.stdout + r.stderr
    ran = "test(s)" in out and ", 0 test(s)" not in out
    return r.returncode, ran, out


def editor_running():
    # Any Unreal process of this project, or one naming no project (tools/unreal_procs.py); another project's run is not ours.
    from unreal_procs import blocking
    return bool(blocking())


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", action="append")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()
    chosen = [s for s in SABOTAGES if not args.only or s[0] in args.only]
    unknown = set(args.only or []) - {s[0] for s in SABOTAGES}
    if unknown:
        print("unknown sabotage(s): %s" % ", ".join(sorted(unknown)))
        return 2
    stale = []
    for name, file, old, *_ in SABOTAGES if args.list else chosen:
        raw = (GAME / file).read_bytes().decode("utf-8")
        count = raw.count(in_file_endings(raw, old))
        if count != 1:
            stale.append("%-30s target occurs %d times in %s" % (name, count, file))
    if args.list:
        for s in SABOTAGES:
            print("%-30s %-28s -> %s" % (s[0], s[1], s[4]))
    if stale:
        print("STALE: update these targets in tools/sabotage_realm.py (nothing was built or run):")
        for line in stale:
            print("  " + line)
        return 2
    if args.list:
        return 0
    if editor_running():
        print("sabotage_realm: an Unreal editor is running; close it first (this never closes it for you)")
        return 2

    missed = []
    for name, file, old, new, test in chosen:
        path = GAME / file
        original = path.read_bytes()
        text = original.decode("utf-8")
        try:
            sabotaged = text.replace(in_file_endings(text, old), in_file_endings(text, new), 1)
            if sabotaged == text:
                # Confirm the sabotage LANDED (docs/09 §1): unchanged code is not a test of anything.
                print("NOLAND   %-28s the target was not replaced; nothing was built" % name, flush=True)
                missed.append(name)
                continue
            path.write_bytes(sabotaged.encode("utf-8"))
            ok, log = build()
            if not ok:
                print("NOBUILD  %-28s the sabotaged source does not compile:\n%s" % (name, log[-2000:]))
                missed.append(name)
                continue
            code, ran, out = run(test)
            caught = ran and code != 0
            print("%s %-28s %s" % ("CAUGHT  " if caught else "MISSED  ", name, test), flush=True)
            if not caught:
                missed.append(name)
        finally:
            path.write_bytes(original)

    ok, log = build()
    clean_ok = ok
    if not ok:
        print("NOBUILD  the clean sources:\n%s" % log[-2000:])
    else:
        for test in sorted({s[4] for s in chosen}):
            code, ran, out = run(test)
            if code != 0 or not ran:
                clean_ok = False
                # Keep the evidence: run_automation reuses one log per filter, so the next run would overwrite it.
                keep = ROOT / "build" / ("sabotage_realm_clean_fail_%s.log" % test.replace(".", "_"))
                keep.write_text(out, encoding="utf-8")
                print("FAILS    clean build: %s (exit %d, ran %s; output kept in %s)" % (test, code, ran, keep))
                for line in out.splitlines():
                    if "Error" in line or "FAIL" in line or "PAW_" in line:
                        print("           " + line.strip()[-300:])
    print("%s  the clean sources" % ("PASS    " if clean_ok else "FAIL    "))
    if missed or not clean_ok:
        print("FAIL  %d sabotage(s) not caught: %s" % (len(missed), ", ".join(missed)))
        return 1
    print("PASS  all %d sabotages caught; the clean build passes" % len(chosen))
    return 0


if __name__ == "__main__":
    sys.exit(main())
